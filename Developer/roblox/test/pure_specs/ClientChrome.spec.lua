		end)
		it("accent glow fade-in targets 0.85", function()
			expect(clientSource:find("accentGlow, EASE_OUT, { BackgroundTransparency = 0.85 }", 1, true)).to.be.a("number")
		end)
		it("accent glow fade-out targets 1", function()
			expect(clientSource:find("accentGlow, fade, { BackgroundTransparency = 1 }", 1, true)).to.be.a("number")
		end)
		it("no 4px accent bar remains", function()
			expect(clientSource:find("accentBar.Size = UDim2.new(0, 4, 1, -14)", 1, true) == nil).to.equal(true)
		end)
	end)

	describe("kqbq.6 marker glow brightening", function()
		it("cast/raid marker glow is 18px wide", function()
			expect(clientSource:find("markerGlow.Size = UDim2.new(0, 18, 1, 10)", 1, true)).to.be.a("number")
		end)
		it("cast/raid marker glow transparency is 0.50", function()
			expect(clientSource:find("markerGlow.BackgroundTransparency = 0.50", 1, true)).to.be.a("number")
		end)
		it("bite marker glow is 18px wide", function()
			expect(clientSource:find("biteMarkerGlow.Size = UDim2.new(0, 18, 1, 10)", 1, true)).to.be.a("number")
