		it("rate label uses AutomaticSize.X", function()
			expect(clientSource:find("AutomaticSize = Enum.AutomaticSize.X", 1, true)).to.be.a("number")
		end)
		it("readyLabel uses claim green Color3", function()
			expect(clientSource:find("Color3.fromRGB(50, 160, 80)", 1, true)).to.be.a("number")
